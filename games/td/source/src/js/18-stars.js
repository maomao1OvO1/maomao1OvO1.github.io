/* ================= 三星评价（按剩余基地血量，MAXHP = 20） ================= */
function starsForHp(v){ return v >= 18 ? 3 : (v >= 12 ? 2 : 1); }
/* 把星数（0~3）转成 ★★☆ 形式的字符串（关卡列表与结算显示）*/
function starStr(n){
  n = Math.max(0, Math.min(3, n | 0));
  var t = '';
  for (var i = 0; i < 3; i++) t += (i < n ? '★' : '☆');
  return t;
}
