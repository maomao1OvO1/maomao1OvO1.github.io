/* ================= 地图：网格 + S 形路径 ================= */
var COLS = 16, ROWS = 10, CELL = 0, OX = 0, OY = 0;   // v6.3：横屏比例（原来 9x14 是竖屏比例，横屏玩只剩中间一条窄带）
/* 网格布局：按 16x10 的 COLS/ROWS 算出单格边长 CELL 与战场居中偏移 OX/OY（resize 后调用，cx/cy 依赖它）*/
function layout(){ CELL = Math.min(W / COLS, H / ROWS); OX = (W - CELL*COLS)/2; OY = (H - CELL*ROWS)/2; }
/* 网格列号 c → 屏幕像素 X（格子中心）：所有绘制与命中判定都用它换算坐标 */
function cx(c){ return OX + c * CELL + CELL/2; }
/* 网格行号 r → 屏幕像素 Y（格子中心）：cx 的行方向对应物 */
function cy(r){ return OY + r * CELL + CELL/2; }

